# 03_financial_impacts.py
# Financial impact of the supplier change the simulator recommends (ROADMAP Section 10).
# Kept apart from the simulator: it only CALLS functions/ and writes to reports/financial_impacts/.
#
# Change evaluated: BEFORE = the least reliable combination of our library candidates,
#                   AFTER  = the simulator's recommended (most reliable) combination.
# Cost per 1,000 vehicles (A14): purchase at Sheet2 distributor prices, plus warranty exposure: every
# warranty failure is a replacement of the failed component at its unit price (E12).
# Conditions: 55 C (as in the Preliminary Results) and the hotter 40/70/105 C profile, 2,920 h (A7).
# Prices (A15): the library's Sheet2 prices; both MCUs are FAMILY PROXIES (C2000 priced as F2800157,
# RH850 as R7F7016843).
# Uncertainty: the simulator's 5,000 paired draws (common random numbers), summarized like the
# course's financial-analysis example: median, standard error and 95% interval for every number.
#
# Run from the project root:  .venv/Scripts/python analysis/03_financial_impacts.py   (~5 seconds)

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.append(str(ROOT))
sys.path.append(str(Path(__file__).resolve().parent))
from caveats import DATA_CAVEAT  # noqa: E402
from functions.candidates import library_candidate, select  # noqa: E402
from functions.finance import combination_costs, compare_costs  # noqa: E402
from functions.library import SLOTS, load_library  # noqa: E402
from functions.simulator import DEFAULT_WARRANTY_HOURS, N_DRAWS, SEED  # noqa: E402

OUT = ROOT / "reports" / "financial_impacts"
TABLES = OUT / "tables"
MISSION, TARGET, FLEET = DEFAULT_WARRANTY_HOURS, 0.999, 1000
CONDITIONS = {"55 C": 55.0, "40/70/105 C profile": [(40, 0.5), (70, 0.3), (105, 0.2)]}
CANDIDATES = ["F280049CPZQR", "R7F7016903AFP-C", "BQ79656PAPRQ1", "LTC6811-1", "ISO7741QDWRQ1",
              "ADuM141E", "TMP4719QDGSRQ1", "UCC21750QDWRQ1", "ADuM4135", "TMCS1101A4UQDRQ1"]
BEFORE, AFTER, SAVING = "before: least reliable suppliers", "after: recommended suppliers", "saving (before - after)"


def candidates(lib):
    """Library parts as candidates, priced from the library's Sheet2 match (family proxy where flagged,
    A15); parts with no library price fall back to the Sheet2 slot average inside select() (A14)."""
    out = []
    for part in CANDIDATES:
        c = library_candidate(part, lib)
        price = lib.set_index("part").loc[part, "unit_price_usd"]
        if pd.notna(price):
            c["unit_price_usd"] = float(price)
        out.append(c)
    return out


def price_source(lib, part, slot):
    """Where each price came from, for the tables (replaces select()'s generic 'entered by user')."""
    r = lib.set_index("part").loc[part]
    if pd.isna(r["unit_price_usd"]):
        return f"Sheet2 average for {slot}"
    proxy = " (family proxy)" if "proxy" in str(r["flag"]) else (" (orderable variant)" if "variant" in str(r["flag"]) else "")
    return f"Sheet2 price of {r['price_part']}{proxy}"


def parts_of(row):
    return [row[s] for s in SLOTS if s in row.index and isinstance(row[s], str)]


def run_condition(profile, lib):
    sel = select(candidates(lib), profile, MISSION, TARGET, fleet_size=FLEET, top=100)
    after_row, before_row = sel.combinations.iloc[0], sel.combinations.iloc[-1]
    cmp = compare_costs(combination_costs(sel, parts_of(before_row)), combination_costs(sel, parts_of(after_row)))
    return sel, before_row, after_row, cmp


def long_table(label, cmp):
    rows = []
    for key in ("failures", "warranty_cost", "purchase_cost", "total_cost"):
        for scen, prefix in ((BEFORE, "before"), (AFTER, "after"), (SAVING, "saving")):
            rows.append({"condition": label, "scenario": scen, "quantity": key, **cmp[f"{prefix}_{key}"]})
    return rows


def price_table(sel, lib):
    t = sel.candidates.copy()
    t["price_source"] = [price_source(lib, n, s) for n, s in zip(t["name"], t["slot"])]
    return t[["slot", "name", "supplier", "unit_price_usd", "price_source", "fit_median", "fit_lower", "fit_upper",
              "warranty_failures_median", "warranty_failures_lower", "warranty_failures_upper",
              "warranty_cost_median", "warranty_cost_lower", "warranty_cost_upper", "purchase_cost",
              "total_cost_median", "total_cost_lower", "total_cost_upper"]].rename(columns={"name": "part"})


def key_numbers(summary, ba, prices55):
    def q(cond, scen, qty, fmt="{:,.2f}"):
        r = ba[(ba["condition"] == cond) & (ba["scenario"] == scen) & (ba["quantity"] == qty)].iloc[0]
        return f"{fmt.format(r['estimate'])} (95% CI {fmt.format(r['lower'])} to {fmt.format(r['upper'])}; SE {fmt.format(r['se'])})"

    lines = ["# Financial Impacts: key numbers (generated by analysis/03_financial_impacts.py)", "",
             DATA_CAVEAT,
             "For the financial result this means: the BEFORE combination is the least reliable by the evidence in",
             "our table, which under-rates the RH850; the purchase difference also depends on MCU proxy prices (A15).",
             "",
             "Change: BEFORE = least reliable supplier combination, AFTER = recommended (most reliable) combination.",
             f"Per {FLEET:,} vehicles, mission {MISSION:,.0f} h (A7); {N_DRAWS:,} paired Monte Carlo draws, seed {SEED}.",
             "Purchase cost: Sheet2 distributor unit prices (Mouser, DigiKey; links in data/prices.csv).",
             "Warranty exposure: each warranty failure is a replacement of the failed component at its unit price",
             "(labour and logistics are not included).",
             "",
             "How warranty exposure is calculated (E12), in every one of the Monte Carlo draws:",
             f"- expected replacements of part i = N x (1 - exp(-lambda_i x t_w)), N = {FLEET:,} vehicles, "
             f"t_w = {MISSION:,.0f} h",
             "- warranty cost = sum over the parts of (expected replacements of part i x unit price of part i)",
             "- total cost = N x sum of unit prices (purchase) + warranty cost",
             "- the draws give the median, SE and 95% interval; before and after use the same draws (paired).",
             "Purchase cost has no uncertainty (fixed prices), so its interval has zero width.", ""]
    for _, s in summary.iterrows():
        c = s["condition"]
        lines += [f"## {c}",
                  f"- Before: {s['before_combination']}",
                  f"- After:  {s['after_combination']}",
                  f"- Purchase cost: before {q(c, BEFORE, 'purchase_cost')}; after {q(c, AFTER, 'purchase_cost')}; "
                  f"saving {q(c, SAVING, 'purchase_cost')}",
                  f"- Expected warranty replacements: before {q(c, BEFORE, 'failures', '{:,.3f}')}; "
                  f"after {q(c, AFTER, 'failures', '{:,.3f}')}; replacements avoided {q(c, SAVING, 'failures', '{:,.3f}')}",
                  f"- Warranty cost (replacements at component price): before {q(c, BEFORE, 'warranty_cost')}; "
                  f"after {q(c, AFTER, 'warranty_cost')}; saving {q(c, SAVING, 'warranty_cost')}",
                  f"- Total cost: before {q(c, BEFORE, 'total_cost')}; after {q(c, AFTER, 'total_cost')}",
                  f"- Saving from the change: {q(c, SAVING, 'total_cost')} per {FLEET:,} vehicles; "
                  f"P(after costs less) = {s['p_after_cheaper']:.3f}; P(after needs fewer replacements) = "
                  f"{s['p_after_fewer_failures']:.3f}", ""]
    lines += ["## Prices used (USD per unit)"]
    for _, r in prices55.iterrows():
        lines.append(f"- {r['slot']}: {r['part']} {r['unit_price_usd']:.2f} ({r['price_source']})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TABLES.mkdir(parents=True, exist_ok=True)
    lib = load_library()

    ba, summary, prices = [], [], {}
    for label, profile in CONDITIONS.items():
        sel, before_row, after_row, cmp = run_condition(profile, lib)
        ba += long_table(label, cmp)
        summary.append({"condition": label, "before_combination": before_row["combination"],
                        "after_combination": after_row["combination"],
                        "p_after_cheaper": cmp["p_after_cheaper"],
                        "p_after_fewer_failures": cmp["p_after_fewer_failures"]})
        prices[label] = price_table(sel, lib)
    ba, summary = pd.DataFrame(ba), pd.DataFrame(summary)

    ba.to_csv(TABLES / "fin_1_before_after.csv", index=False)
    summary.to_csv(TABLES / "fin_2_scenarios.csv", index=False)
    pd.concat(prices, names=["condition"]).reset_index(level=0).to_csv(TABLES / "fin_3_candidates_cost.csv", index=False)
    (OUT / "key_numbers_financial.md").write_text(key_numbers(summary, ba, prices["55 C"]), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: 3 tables, key_numbers_financial.md")
